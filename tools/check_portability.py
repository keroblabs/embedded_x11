#!/usr/bin/env python3
"""Verify the compiled windowing boundary and reproduce its guarded source patches."""

from __future__ import annotations

import argparse
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
import difflib
import hashlib
import json
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "patches/manifest.json"
TARGETS = ("wmb_tinyx", "wmb_kdrive", "wmb_xlib", "wmb_xfont",
           "wmb_transport_core", "wmb_jwm", "wmb_applications", "wmb_desktop",
           "wmb_api_runtime", "wmb_metrics")
NATIVE_HEADER = re.compile(
    r"^(?:sys/|linux/|netinet/|xcb/|SDL|"
    r"(?:netdb|pwd|grp|unistd|signal|fcntl|dirent|termios|poll|pthread|dlfcn)\.h$|"
    r"X11/(?:Xpoll|Xthreads|Xos_r)\.h$|X11/xtrans/|"
    r".*(?:hal_drivers\.h|sdl_[^/]*\.h)$)"
)
NATIVE_SYMBOL = re.compile(
    r"^(?:socket|socketpair|bind|listen|accept4?|connect|select|pselect|pselect6|poll|ppoll|"
    r"epoll_\w+|readv|writev|fcntl|ioctl|getpeername|getsockname|getsockopt|setsockopt|"
    r"recv\w*|send\w*|fork|vfork|exec\w*|posix_spawn\w*|waitpid|wait|"
    r"sigaction|signal|sigprocmask|sigemptyset|sigaddset|setitimer|alarm|kill|"
    r"setrlimit|getrlimit|getuid|geteuid|getgid|getegid|setuid|seteuid|setgid|setegid|"
    r"getpid|getpgrp|setpgid|uname|gethostname|getaddrinfo|freeaddrinfo|getnameinfo|"
    r"getpwnam|getpwuid|sysconf|gettimeofday|clock_gettime|time|ctime|_exit|sleep|usleep|nanosleep|"
    r"getenv|setenv|unsetenv|setlocale|localeconv|"
    r"open|close|read|write|pipe|dup2?|link|unlink|lseek|stat|fstat|access|"
    r"opendir|readdir|fopen|fdopen|fclose|fread|fgets|fchmod|popen|pclose|fileno|"
    r"dlopen|dlsym|dlclose|pthread_\w+|xcb_\w+|_XSERVTrans\w*|_XConnectDisplay)$"
)


@dataclass(frozen=True)
class Patch:
    file: str
    patch: str
    selector: str
    reason: str
    probe: str = ""
    base_sha256: str = ""
    result_sha256: str = ""
    added: int = 0
    removed: int = 0


@dataclass(frozen=True)
class Compile:
    file: Path
    directory: Path
    arguments: list[str]
    target: str


def run(arguments: list[str], cwd: Path = ROOT, data: bytes | None = None) -> bytes:
    result = subprocess.run(arguments, cwd=cwd, input=data, capture_output=True)
    if result.returncode:
        raise RuntimeError(
            f"Command failed ({result.returncode}): {shlex.join(arguments)}\n"
            + result.stderr.decode(errors="replace")[-6000:]
        )
    return result.stdout


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def original(baseline: str, file: str) -> bytes:
    return run(["git", "show", f"{baseline}:{file}"])


def patch_bytes(file: str, before: bytes, after: bytes) -> bytes:
    return b"".join(
        difflib.diff_bytes(
            difflib.unified_diff,
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=("a/" + file).encode(),
            tofile=("b/" + file).encode(),
        )
    )


def licenses_unchanged(before: bytes, after: bytes) -> bool:
    return all(
        notice in after
        for notice in re.findall(rb"/\*.*?\*/", before, re.DOTALL)
        if any(word in notice.lower() for word in (b"copyright", b"permission", b"license"))
    )


def regenerate() -> None:
    manifest = json.loads(MANIFEST.read_text())
    rows = []
    for item in manifest["files"]:
        before = original(manifest["baseline"], item["file"])
        after = (ROOT / item["file"]).read_bytes()
        patch = patch_bytes(item["file"], before, after)
        if not patch or not licenses_unchanged(before, after):
            raise RuntimeError(f"Empty patch or changed license: {item['file']}")
        destination = ROOT / "patches" / item["patch"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(patch)
        item["base_sha256"] = digest(before)
        item["result_sha256"] = digest(after)
        item["added"] = sum(line.startswith(b"+") and not line.startswith(b"+++") for line in patch.splitlines())
        item["removed"] = sum(line.startswith(b"-") and not line.startswith(b"---") for line in patch.splitlines())
        rows.append(
            f"| [{item['patch']}]({item['patch']}) | `{item['file']}` | "
            f"`{item['selector']}` | +{item['added']}/-{item['removed']} | {item['reason']} |"
        )
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    (ROOT / "patches/MANIFEST.md").write_text(
        "# Guarded source patch manifest\n\n"
        "Generated by `python3 tools/check_portability.py --regenerate-patches` "
        "from the repository root. Do not edit patch output by hand.\n\n"
        f"Baseline: `{manifest['baseline']}`. {manifest['baseline_description']}\n\n"
        "Each patch applies from the repository root to the exact original file "
        "identified by its SHA-256 in [manifest.json](manifest.json). "
        "The verifier checks replay, final bytes, license notices, budgets, and "
        "undefined-selector preprocessing against that baseline.\n\n"
        "| Patch | Upstream file | Primary selector | LOC delta | Reason |\n"
        "|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\nShared `Xos.h` also selects the standard-C branch for `WMB_INPROC` "
        "and `WMB_FONT_BUILTINS_ONLY`. Every selector is presence-based. "
        "New owned adapters and source exclusions are selected by CMake, not "
        "copied into this upstream patch series.\n\n"
        "Pinned libXfont repairs/profile patches remain in "
        "[cmake/patches/](../cmake/patches/) and are applied with a checked hash "
        "by [WmbXfont.cmake](../cmake/WmbXfont.cmake). "
        "JWM's P7 sites preserve the same imported native reference discipline.\n"
    )
    print(f"Generated {len(rows)} guarded source patches and manifest")


def verify_patches(patches: list[Patch], baseline: str, directory: Path) -> None:
    expected = {item.file for item in patches}
    for item in patches:
        before = original(baseline, item.file)
        after = (ROOT / item.file).read_bytes()
        if digest(before) != item.base_sha256 or digest(after) != item.result_sha256:
            raise RuntimeError(f"Manifest hash mismatch: {item.file}; review before regenerating")
        if not licenses_unchanged(before, after):
            raise RuntimeError(f"Original license bytes changed: {item.file}")
        destination = directory / item.file
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(before)
        patch = ROOT / "patches" / item.patch
        if patch.read_bytes() != patch_bytes(item.file, before, after):
            raise RuntimeError(f"Patch does not reproduce the source delta: {item.patch}")
        run(["git", "apply", "--check", str(patch)], directory)
        run(["git", "apply", str(patch)], directory)
        if destination.read_bytes() != after:
            raise RuntimeError(f"Replayed source mismatch: {item.file}")
        destination.write_bytes(before)
    changed = {
        file for file in run([
            "git", "diff", "--name-only", "--diff-filter=M", baseline,
            "--", "tinyx", "libX11", "X11", "jwm",
        ]).decode().splitlines() if Path(file).suffix in (".c", ".h")
    }
    if changed != expected:
        raise RuntimeError(f"Upstream patch coverage mismatch: {sorted(changed ^ expected)}")
    print(f"PASS patch replay, original notices and exact coverage: {len(patches)} files")


def compile_entries(build: Path) -> list[Compile]:
    result = []
    for item in json.loads((build / "compile_commands.json").read_text()):
        arguments = shlex.split(item["command"])
        file = Path(item["file"]).resolve()
        if any(file.is_relative_to(ROOT / path) for path in (
            "framework", "hal", "linux_hosted/sdl_drivers", "linux_hosted/sdl_library",
        )) and any(flag in item["command"] for flag in (
            "-DWMB_DEVEL", "-DWMB_INPROC", "-DWMB_APP_OPAQUE", "_XSERVER64", "/generated/tinyx/",
        )):
            raise RuntimeError(f"Windowing ABI flags leaked below the contract: {file}")
        matches = [target for target in TARGETS if f"/{target}.dir/" in item["command"]]
        if matches:
            result.append(Compile(file, Path(item["directory"]), arguments, matches[0]))
    if set(entry.target for entry in result) != set(TARGETS):
        raise RuntimeError("Compile database does not contain all windowing cohorts")
    return result


def compiler_flags(entry: Compile, overlay: Path | None = None) -> list[str]:
    result = [entry.arguments[0]]
    index = 1
    while index < len(entry.arguments):
        argument = entry.arguments[index]
        if argument == "-o":
            index += 2
            continue
        if argument == "-c" or argument == str(entry.file):
            index += 1
            continue
        if overlay is not None and argument.startswith("-I"):
            path = Path(argument[2:]).resolve()
            if path.is_relative_to(ROOT):
                result.append("-I" + str(overlay / path.relative_to(ROOT)))
        result.append(argument)
        index += 1
    return result


def native_includes(output: str, roots: tuple[Path, ...],
                    regex_type_header: Path | None = None) -> set[str]:
    origin = ""
    prefixes = tuple(str(root) + "/" for root in roots)
    owned = False
    number = 0
    violations = set()
    for line in output.splitlines():
        marker = re.match(r'# (\d+) "([^"]+)"', line)
        if marker:
            origin = marker[2]
            owned = origin.startswith(prefixes) or "/X11/" in origin
            number = int(marker[1])
            continue
        include = re.match(r'#include [<"]([^>"]+)[>"]', line)
        data_only = (include is not None and include[1] == "sys/types.h" and
                     regex_type_header is not None and Path(origin).resolve() == regex_type_header)
        if include and owned and NATIVE_HEADER.match(include[1]) and not data_only:
            violations.add(f"{Path(origin).resolve()}:{number}: {include[1]}")
        number += 1
    return violations


def audit_sources(entries: list[Compile], build: Path) -> None:
    font_entries = [entry for entry in entries if entry.target == "wmb_xfont" and not entry.file.is_relative_to(ROOT)]
    roots = (ROOT, build, *sorted({entry.file.parent for entry in font_entries}))
    regex_types = build / "generated/regex/tre/tre.h"
    regex_types = regex_types.resolve() if regex_types.exists() else None

    def scan(entry: Compile) -> set[str]:
        if entry.target in ("wmb_xlib", "wmb_jwm", "wmb_api_runtime") and any(
            token in " ".join(entry.arguments) for token in ("-DWMB_DEVEL", "_XSERVER64", "/generated/tinyx")
        ):
            raise RuntimeError(f"Server ABI leaked into client: {entry.file}")
        output = run(compiler_flags(entry) + ["-E", "-dI", str(entry.file)], entry.directory)
        return native_includes(output.decode(errors="replace"), roots, regex_types)

    violations: set[str] = set()
    with ThreadPoolExecutor(max_workers=3) as pool:
        for found in pool.map(scan, entries):
            violations.update(found)
    if violations:
        raise RuntimeError("Active native headers:\n" + "\n".join(sorted(violations)))
    print(f"PASS active header boundary: {len(entries)} actual translation units")


def preprocess(entry: Compile, selector: str, value: str | None, overlay: Path | None) -> bytes:
    file = entry.file
    if overlay is not None and file.is_relative_to(ROOT) and (overlay / file.relative_to(ROOT)).exists():
        file = overlay / file.relative_to(ROOT)
    prefix = ""
    if entry.target in ("wmb_xlib", "wmb_xfont"):
        prefix = "#include <config.h>\n"
    if entry.target == "wmb_xlib" and value is None:
        # Native probes need host I/O features and modern protocol annotations.
        prefix += (
            "#define HAVE_SYS_IOCTL_H 1\n#define HAVE_UNISTD_H 1\n"
            "#define HAVE_SYS_SOCKET_H 1\n"
            "#define _X_COLD __attribute__((cold))\n"
            "#define _X_UNUSED __attribute__((unused))\n"
        )
    prefix += f"#undef {selector}\n"
    if value is not None:
        prefix += f"#define {selector} {value}\n"
    prefix += f'#include "{file}"\n'
    flags = compiler_flags(entry, overlay)
    if entry.target == "wmb_jwm":
        if value is None:
            prefix = (
                "#define _X_COLD __attribute__((cold))\n"
                "#define _X_UNUSED __attribute__((unused))\n"
            ) + prefix
            flags.append("-UWMB_INPROC")
            native = ROOT / "docs/reference/jwm-config.reference.h"
            if overlay is None:
                # The actual sources resolve ../config.h through this probe-only include path.
                directory = entry.directory / "jwm-native-probe"
                (directory / "src").mkdir(parents=True, exist_ok=True)
                (directory / "config.h").write_bytes(native.read_bytes())
            else:
                directory = overlay / "jwm"
                (directory / "src").mkdir(parents=True, exist_ok=True)
                (directory / "config.h").write_bytes(native.read_bytes())
            flags += ["-I" + str(directory / "src")]
    flags += ["-Wno-builtin-macro-redefined", "-D__LINE__=0", f"-ffile-prefix-map={ROOT}=SOURCE"]
    if overlay is not None:
        flags.append(f"-ffile-prefix-map={overlay}=SOURCE")
    return run(flags + ["-E", "-P", "-x", "c", "-"], entry.directory, prefix.encode())


def audit_reference(entries: list[Compile], patches: list[Patch], overlay: Path) -> None:
    sources = {
        ROOT / (item.probe or item.file): item
        for item in patches if item.file.endswith(".c") or item.probe
    }
    checked = 0
    for entry in entries:
        if entry.file not in sources:
            continue
        item = sources[entry.file]
        before = preprocess(entry, item.selector, None, overlay)
        after = preprocess(entry, item.selector, None, None)
        if before != after:
            difference = list(difflib.unified_diff(
                before.decode(errors="replace").splitlines(),
                after.decode(errors="replace").splitlines(), n=2
            ))
            raise RuntimeError(f"Reference preprocessing changed: {item.file}\n" + "\n".join(difference[:35]))
        run([entry.arguments[0], "-std=gnu11", "-fsyntax-only", "-x", "cpp-output", "-"],
            entry.directory, after)
        variants = [preprocess(entry, item.selector, value, None) for value in ("1", "0", "")]
        if not variants[0] == variants[1] == variants[2]:
            raise RuntimeError(f"Value-aware project selector: {item.file}")
        checked += 1
    if checked != len(sources):
        raise RuntimeError("Not every patched C source was checked")
    print(f"PASS native compilation/preprocessing and one/zero/empty variants: {checked} sources plus included headers")


def imported_symbols(output: str) -> set[str]:
    symbols = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) >= 2 and fields[-2] == "U":
            symbol = fields[-1].split("@", 1)[0]
            symbols.add(symbol)
    return symbols


def forbidden_symbols(output: str) -> set[str]:
    return {symbol for symbol in imported_symbols(output) if NATIVE_SYMBOL.fullmatch(symbol)}


def audit_symbols(build: Path) -> None:
    targets = json.loads((build / "portability-targets.json").read_text())
    for path in [*targets["archives"], targets["probe"]]:
        output = run(["nm", "-u", path]).decode()
        symbols = forbidden_symbols(output)
        if symbols:
            raise RuntimeError(f"Native imports in {path}: {sorted(symbols)}")
        if path in targets["archives"]:
            raw_allocators = imported_symbols(output) & {
                "malloc", "calloc", "realloc", "free", "strdup", "strndup",
                "aligned_alloc", "posix_memalign", "wmb_alloc", "wmb_free",
            }
            if raw_allocators:
                raise RuntimeError(f"Unattributed allocation imports in {path}: {sorted(raw_allocators)}")
    print("PASS native symbol boundary in every complete archive and the no-backend image")
    print("PASS allocation attribution: no selected windowing archive bypasses owner accounting")


def verify(build: Path) -> None:
    manifest = json.loads(MANIFEST.read_text())
    patches = [Patch(**item) for item in manifest["files"]]
    counts = Counter(item.file.split("/", 1)[0] for item in patches)
    for tree, count in counts.items():
        if count > manifest["caps"][tree]:
            raise RuntimeError(f"Guard budget exceeded: {tree}: {count}")
    expected_paths = {str(ROOT / "patches" / item.patch) for item in patches}
    actual_paths = {str(path) for path in (ROOT / "patches").glob("*/*.patch")}
    if expected_paths != actual_paths:
        raise RuntimeError("Patch directory differs from the manifest")
    entries = compile_entries(build)
    with tempfile.TemporaryDirectory(prefix="wmb-p6-", dir=build) as directory:
        overlay = Path(directory)
        verify_patches(patches, manifest["baseline"], overlay)
        audit_reference(entries, patches, overlay)
    audit_sources(entries, build)
    audit_symbols(build)
    run([sys.executable, str(ROOT / "tools/jwm_namespace.py"),
         "--archive", str(build / "jwm/libwmb_jwm.a")])
    print("PASS complete JWM symbol isolation")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path)
    parser.add_argument("--regenerate-patches", action="store_true")
    args = parser.parse_args()
    try:
        if args.regenerate_patches:
            regenerate()
        elif args.build_dir is not None:
            verify(args.build_dir.resolve())
        else:
            parser.error("--build-dir is required unless regenerating patches")
    except (OSError, ValueError, RuntimeError) as error:
        print(f"P6 portability FAIL: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
