#!/usr/bin/env python3
"""Generate/check compiler-level namespaces for JWM's external symbols."""

import argparse
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "jwm/wmb/jwm_namespace.h"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    output = subprocess.check_output(
        ["nm", "-g", "--defined-only", str(args.archive)], text=True
    )
    names = set()
    unscoped = []
    for line in output.splitlines():
        fields = line.split()
        if len(fields) != 3 or fields[1] not in "TDBRCGSWVI":
            continue
        name = fields[2]
        if name.startswith(("WmbJwm_", "__")) or name == "Jwm_Main":
            continue
        if name.startswith("Jwm_"):
            name = name[4:]
        else:
            unscoped.append(name)
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise SystemExit(f"Unrepresentable JWM symbol: {name}")
        names.add(name)
    header = (
        "#ifndef WMB_JWM_NAMESPACE_H\n#define WMB_JWM_NAMESPACE_H\n"
        "/* Generated by tools/jwm_namespace.py; C field names remain unchanged. */\n"
        "#if defined(WMB_INPROC)\n#define main Jwm_Main\n"
        "#pragma redefine_extname exit WmbJwm_Terminate\n"
        + "".join(f"#pragma redefine_extname {name} Jwm_{name}\n" for name in sorted(names))
        + "/* These definitions lack a prior prototype in their original TU. */\n"
        "struct KeyNode;\nstruct TokenNode;\n"
        "extern void RemoveDuplicates(struct KeyNode *);\n"
        "extern void ParseTrayButtonStyle(const struct TokenNode *);\n"
        "extern void GrabServer(void);\nextern void UngrabServer(void);\n"
        + "#endif\n#endif\n"
    )
    if args.write:
        HEADER.write_text(header)
        print(f"Generated {len(names)} JWM namespace bindings")
    else:
        if unscoped or HEADER.read_text() != header:
            raise SystemExit(f"JWM namespace mismatch/unscoped exports: {unscoped}")
        print(f"PASS JWM namespace: {len(names)} external symbols, no unscoped exports")


if __name__ == "__main__":
    main()
