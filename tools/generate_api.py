#!/usr/bin/env python3
"""Generate the append-only application ABI from api.def and audit Xlib macros."""
import argparse
import json
import re
from pathlib import Path
import generate_rpc

ROOT = Path(__file__).resolve().parents[1]
DEFINITION = ROOT / "transport/api/api.def"
FROZEN = ROOT / "docs/reference/api-v1.json"
BANNER = "/* Generated by tools/generate_api.py; edit transport/api/api.def. */\n"


def macro_inventory() -> dict[str, tuple[str, str]]:
    source = (ROOT / "libX11/include/X11/Xlib.h").read_text().replace("\\\n", " ")
    macros = {
        match[1]: (match[2], match[3])
        for match in re.finditer(
            r"^#\s*define\s+(\w+)\(([^)]*)\)\s*(.*)$", source, re.MULTILINE
        )
    }
    selected = {
        name for name, (_, body) in macros.items()
        if "->" in body or "_XPrivDisplay" in body
    }
    while True:
        added = {
            name for name, (_, body) in macros.items()
            if any(re.search(r"\b" + re.escape(other) + r"\s*\(", body)
                   for other in selected)
        }
        if added <= selected:
            return {name: macros[name] for name in sorted(selected)}
        selected |= added


def parameters(entry: dict, names: bool = True) -> str:
    return ", ".join(
        param["type"] + (f" p{index}" if names else "")
        for index, param in enumerate(entry["params"])
    ) or "void"


def invocation(entry: dict, prefix: str = "") -> str:
    return ", ".join(f"{prefix}p{index}" for index in range(len(entry["params"])))


def header(definition: dict, functions: list[dict], version: int) -> str:
    result = BANNER + """#ifndef WMB_API_H
#define WMB_API_H
#include <stdint.h>
#if defined(WMB_APP_OPAQUE)
#include "wmb_app_namespace.h"
#endif
#include <X11/Xlib.h>
#include <X11/Xutil.h>
#ifdef __cplusplus
extern "C" {
#endif
"""
    result += f"#define WMB_API_MAGIC UINT32_C({definition['magic']})\n"
    result += f"#define WMB_API_VERSION {version}u\n"
    result += f"#define WMB_API_SLOT_COUNT {len(functions)}u\n"
    result += """#define WMB_API_LAYOUT ((uint32_t)(sizeof(void *) | (sizeof(long) << 8) | (sizeof(XEvent) << 16)))
typedef struct { uint32_t magic, version, count, layout; } wmb_api_header_t;
typedef struct wmb_api {
    uint32_t magic, version, count, layout;
"""
    for entry in functions:
        result += f"    {entry['returns']} (*{entry['name']})({parameters(entry)});\n"
    result += """} wmb_api_t;
/* The first 16 bytes must be readable; the supplied table is trusted immutable data. */
int wmb_bind(const wmb_api_t *table);
"""
    for entry in functions:
        if entry["name"].startswith("wmb"):
            result += f"{entry['returns']} {entry['name']}({parameters(entry)});\n"
    return result + """#ifdef __cplusplus
}
#endif
#endif
"""


def wrappers(functions: list[dict]) -> str:
    result = BANNER + """#include "wmb_api.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#ifdef WMB_WRAPPER_TEST_PREFIX
#define WRAP(name) wmb_app_##name
#else
#define WRAP(name) name
#endif
static const wmb_api_t *bound;
static int reject(int status, const char *reason)
{
    fprintf(stderr, "WMB ABI: %s\\n", reason);
    return status;
}
int WRAP(wmb_bind)(const wmb_api_t *table)
{
    wmb_api_header_t header;
    bound = NULL;
    if (!table) return reject(-1, "NULL table");
    memcpy(&header, table, sizeof(header));
    if (header.magic != WMB_API_MAGIC) return reject(-2, "wrong ABI magic");
    if (header.version < WMB_API_VERSION) return reject(-3, "provider version is too old");
    if (header.count < WMB_API_SLOT_COUNT) return reject(-4, "provider has too few slots");
    if (header.layout != WMB_API_LAYOUT) return reject(-5, "incompatible C data model");
"""
    for entry in functions:
        result += f"    if (!table->{entry['name']}) return reject(-6, \"missing required API slot\");\n"
    result += """    bound = table;
    return 0;
}
static _Noreturn void unbound(void)
{
    fputs("WMB ABI: application used an unbound API\\n", stderr);
    abort();
}
"""
    for entry in functions:
        result += f"{entry['returns']} WRAP({entry['name']})({parameters(entry)})\n{{\n"
        result += "    if (!bound) unbound();\n    "
        if entry["returns"] != "void":
            result += "return "
        result += f"bound->{entry['name']}({invocation(entry)});\n}}\n"
    return result


def calls_header(functions: list[dict]) -> str:
    result = BANNER + """#ifndef WMB_API_CALLS_H
#define WMB_API_CALLS_H
#include "wmb_api.h"
#include <stdatomic.h>
typedef enum {
"""
    for index, entry in enumerate(functions):
        result += f"    WMB_SLOT_{entry['name']} = {index},\n"
    result += """} WmbApiSlot;
typedef struct WmbApiCall WmbApiCall;
struct WmbApiCall {
    WmbApiCall *next;
    unsigned slot;
    int status;
    atomic_bool done, entered;
    union {
"""
    for entry in functions:
        fields = " ".join(
            f"{param['type']} p{index};" for index, param in enumerate(entry["params"])
        ) or "char unused;"
        result += f"        struct {{ {fields} }} {entry['name']};\n"
    result += "    } args;\n    union {\n"
    for entry in functions:
        if entry["returns"] != "void":
            result += f"        {entry['returns']} {entry['name']};\n"
    return result + """    } result;
};
int wmb_gateway_submit(WmbApiCall *call);
void wmb_api_execute(WmbApiCall *call);
const wmb_api_t *wmb_api_native_table(void);
#endif
"""


def native_source(functions: list[dict]) -> str:
    result = BANNER + '#include "api_internal.h"\n'
    for entry in functions:
        result += f"static {entry['returns']} direct_{entry['name']}({parameters(entry)})\n{{\n"
        result += "    wmb_api_require_owner();\n    "
        if entry["returns"] != "void":
            result += "return "
        result += f"{entry.get('native', entry['name'])}({invocation(entry)});\n}}\n"
    result += "static const wmb_api_t native_api = {\n"
    result += "    .magic = WMB_API_MAGIC, .version = WMB_API_VERSION,\n"
    result += "    .count = WMB_API_SLOT_COUNT, .layout = WMB_API_LAYOUT,\n"
    for entry in functions:
        result += f"    .{entry['name']} = direct_{entry['name']},\n"
    result += """};
const wmb_api_t *wmb_api_native_table(void) { return &native_api; }
void wmb_api_execute(WmbApiCall *call)
{
    wmb_api_require_owner();
    switch (call->slot) {
"""
    for entry in functions:
        name = entry["name"]
        result += f"    case WMB_SLOT_{name}:\n        "
        if entry["returns"] != "void":
            result += f"call->result.{name} = "
        result += entry.get("native", name) + "("
        result += invocation(entry, f"call->args.{name}.") + ");\n        break;\n"
    return result + """    default:
        fputs("WMB ABI: invalid native operation\\n", stderr);
        call->status = -1;
    }
}
"""


def gateway_source(functions: list[dict]) -> str:
    result = BANNER
    for entry in functions:
        name = entry["name"]
        result += f"static {entry['returns']} gateway_{name}({parameters(entry)})\n{{\n"
        if name == "wmbYield":
            result += "    return wmb_gateway_foreign_yield(p0);\n}\n"
            continue
        result += f"    WmbApiCall call = {{.slot = WMB_SLOT_{name}}};\n"
        for index in range(len(entry["params"])):
            result += f"    call.args.{name}.p{index} = p{index};\n"
        if name == "XOpenDisplay":
            result += "    if (wmb_gateway_submit(&call)) return NULL;\n"
        else:
            result += "    if (wmb_gateway_submit(&call)) wmb_api_fatal(\"foreign API call failed\");\n"
        if entry["returns"] != "void":
            result += f"    return call.result.{name};\n"
        result += "}\n"
    result += "static const wmb_api_t foreign_api WMB_API_PLACEMENT = {\n"
    result += "    .magic = WMB_API_MAGIC, .version = WMB_API_VERSION,\n"
    result += "    .count = WMB_API_SLOT_COUNT, .layout = WMB_API_LAYOUT,\n"
    for entry in functions:
        result += f"    .{entry['name']} = gateway_{entry['name']},\n"
    result += "};\n"
    result += """static bool call_display(WmbApiCall *call, Display **display)
{
    switch (call->slot) {
"""
    for entry in functions:
        if entry["params"] and entry["params"][0]["kind"] == "display":
            result += f"    case WMB_SLOT_{entry['name']}: *display = call->args.{entry['name']}.p0; return true;\n"
        elif entry["params"] and entry["params"][0]["kind"] == "screen":
            result += f"    case WMB_SLOT_{entry['name']}:\n"
            result += f"        *display = call->args.{entry['name']}.p0 ? XDisplayOfScreen(call->args.{entry['name']}.p0) : NULL;\n"
            result += "        return true;\n"
    return result + "    default: return false;\n    }\n}\n"


def prefix_header(functions: list[dict]) -> str:
    result = BANNER + '#include "wmb_api.h"\n'
    result += 'int wmb_app_wmb_bind(const wmb_api_t *table);\n'
    for entry in functions:
        result += f"{entry['returns']} wmb_app_{entry['name']}({parameters(entry)});\n"
        result += f"#define {entry['name']} wmb_app_{entry['name']}\n"
    return result


def namespace_header(functions: list[dict]) -> str:
    result = BANNER + """#ifndef WMB_APP_NAMESPACE_H
#define WMB_APP_NAMESPACE_H
#if !defined(__GNUC__) && !defined(__clang__)
#error "The application SDK requires compiler external-name pragma support"
#endif
/* Only linker names change; function-pointer field names remain ordinary Xlib names. */
"""
    for index, entry in enumerate(functions):
        result += f"#pragma redefine_extname {entry['name']} wba{index}\n"
    return result + "#endif\n"


def fake_source(functions: list[dict]) -> str:
    result = BANNER + '#include "wmb_api.h"\n'
    for entry in functions:
        result += f"static {entry['returns']} fake_{entry['name']}({parameters(entry)})\n{{\n"
        for index in range(len(entry["params"])):
            result += f"    (void)p{index};\n"
        if entry["returns"] != "void":
            result += "    return " + ("42" if entry["name"] == "XDefaultScreen" else "0") + ";\n"
        result += "}\n"
    result += "void wmb_fake_table(wmb_api_t *table)\n{\n    *table = (wmb_api_t){\n"
    result += "        .magic = WMB_API_MAGIC, .version = WMB_API_VERSION,\n"
    result += "        .count = WMB_API_SLOT_COUNT, .layout = WMB_API_LAYOUT,\n"
    for entry in functions:
        result += f"        .{entry['name']} = fake_{entry['name']},\n"
    return result + "    };\n}\n"


def outputs(definition: dict, frozen: dict) -> dict[Path, str]:
    functions = definition["functions"]
    macros = macro_inventory()
    if set(macros) != set(definition["macros"]):
        raise ValueError(f"unhandled Xlib macros: {set(macros) ^ set(definition['macros'])}")
    frozen_functions = frozen["functions"]
    if definition["magic"] != frozen["magic"] or functions[:len(frozen_functions)] != frozen_functions:
        raise ValueError("the independently frozen ABI v1 prefix changed")
    if definition["macros"] != frozen["macros"]:
        raise ValueError("ABI v1 macro bindings changed")
    names = {entry["name"] for entry in functions}
    if len(names) != len(functions) or not set(definition["macros"].values()) <= names:
        raise ValueError("duplicate or unimplemented API/macro slot")
    last_version = 1
    for entry in functions:
        if entry["since"] < last_version or entry["since"] > definition["version"]:
            raise ValueError("new ABI slots must be appended in version order")
        if len(entry["params"]) > 16:
            raise ValueError("host codec parameter limit exceeded")
        last_version = entry["since"]
    compat = BANNER + '#ifndef WMB_XLIB_COMPAT_H\n#define WMB_XLIB_COMPAT_H\n#include "wmb_api.h"\n'
    for name, function in definition["macros"].items():
        compat += f"#undef {name}\n#define {name} {function}\n"
    compat += "#endif\n"
    macro_test = BANNER + '#include "wmb_xlib_compat.h"\n'
    macro_test += "void wmb_test_all_macros(Display *dpy, Screen *s, int scr)\n{\n"
    for name, (params, _) in macros.items():
        macro_test += f"    (void){name}({params});\n"
    macro_test += "}\n"
    generated = {
        ROOT / "transport/api/wmb_api.h": header(definition, functions, definition["version"]),
        ROOT / "transport/api/wmb_api_table.c": native_source(functions),
        ROOT / "transport/api/api_calls.h": calls_header(functions),
        ROOT / "transport/api/gateway_generated.inc": gateway_source(functions),
        ROOT / "wrapper/libX11-app/wrappers.c": wrappers(functions),
        ROOT / "wrapper/libX11-app/wmb_xlib_compat.h": compat,
        ROOT / "wrapper/libX11-app/wmb_app_namespace.h": namespace_header(functions),
        ROOT / "transport/api/tests/all_macros.c": macro_test,
        ROOT / "transport/api/tests/fake_table.c": fake_source(functions),
        ROOT / "docs/xlib-display-macros.txt": (
            "# Generated by tools/generate_api.py from canonical libX11/include/X11/Xlib.h\n"
            + "".join(f"{name}({params}) -> {definition['macros'][name]}\n"
                      for name, (params, _) in macros.items())
        ),
    }
    legacy = ROOT / "wrapper/libX11-app/v1"
    generated[legacy / "wmb_api.h"] = header(frozen, frozen_functions, 1)
    generated[legacy / "wrappers.c"] = wrappers(frozen_functions)
    generated[legacy / "wmb_test_wrappers.h"] = prefix_header(frozen_functions)
    generated[legacy / "wmb_app_namespace.h"] = namespace_header(frozen_functions)
    generated.update(generate_rpc.outputs(ROOT, definition, BANNER, parameters))
    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--freeze-v1", action="store_true",
                        help="Initial creation only; refuses to rewrite an existing ABI baseline")
    args = parser.parse_args()
    definition = json.loads(DEFINITION.read_text())
    if args.freeze_v1:
        frozen = {**definition, "version": 1,
                  "functions": [f for f in definition["functions"] if f["since"] == 1]}
        with FROZEN.open("x") as stream:
            stream.write(json.dumps(frozen, indent=2) + "\n")
    frozen = json.loads(FROZEN.read_text())
    stale = []
    for path, content in outputs(definition, frozen).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Stale generated ABI output: " + ", ".join(stale))
    print(f"ABI generation {'check' if args.check else 'write'}: "
          f"{len(frozen['functions'])} frozen v1 / {len(definition['functions'])} current slots; "
          f"{len(definition['macros'])} opaque macros PASS")


if __name__ == "__main__":
    main()
